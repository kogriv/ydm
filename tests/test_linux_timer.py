#!/usr/bin/env python3
"""The PC's scheduled sync: generated systemd user units, and desktop cards.

The units are generated by tools/linux/install_timer.sh rather than kept as
templates, so what is tested is the generator. `render` changes nothing on the
machine; `install`/`remove` talk to the user's systemd and are not run here.
"""

from __future__ import annotations

import os
import stat
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

SCRIPT = ROOT / "tools" / "linux" / "install_timer.sh"


def fake_rclone(directory: str, version: str) -> str:
    path = os.path.join(directory, "rclone")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(f'#!/bin/sh\necho "rclone {version}"\n')
    os.chmod(path, os.stat(path).st_mode | stat.S_IXUSR)
    return path


class TestRender(unittest.TestCase):
    def render(self, version="v1.75.2", mirror=True, **env):
        with tempfile.TemporaryDirectory() as tmp:
            root = os.path.join(tmp, "ya_disk")
            if mirror:
                os.makedirs(root)
            full = dict(os.environ, YDM_RCLONE=fake_rclone(tmp, version), YDM_LOCAL_ROOT=root)
            full.update(env)
            proc = subprocess.run(["bash", str(SCRIPT), "render"], capture_output=True,
                                  text=True, env=full)
            return proc, root, full["YDM_RCLONE"]

    def test_service_runs_the_named_rclone_on_the_mirror(self):
        proc, root, binary = self.render()
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertIn(f"Environment=YDM_RCLONE={binary}", proc.stdout)
        self.assertIn(f"sync_bisync.py run --local-root {root} --apply", proc.stdout)
        self.assertIn(f"WorkingDirectory={ROOT}", proc.stdout)
        self.assertIn("Environment=YDM_NOTIFY_DESKTOP=1", proc.stdout)

    def test_service_never_resyncs(self):
        # The timer must not establish a baseline on its own.
        proc, _root, _binary = self.render()
        self.assertNotIn("resync", proc.stdout.split("# --- ydm-bisync.timer")[0].split("ExecStart=")[1].splitlines()[0])

    def test_timer_period(self):
        proc, _root, _binary = self.render(YDM_PERIOD="45min")
        self.assertIn("OnUnitInactiveSec=45min", proc.stdout)

    def test_old_rclone_is_refused(self):
        proc, _root, _binary = self.render(version="v1.60.1-DEV")
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("older than 1.66", proc.stderr)

    def test_missing_mirror_is_refused(self):
        proc, _root, _binary = self.render(mirror=False)
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("does not exist", proc.stderr)


class TestDesktopCards(unittest.TestCase):
    def test_off_unless_asked(self):
        from tools.sync_common import notify
        with mock.patch.dict(os.environ, {}, clear=False), \
                mock.patch("tools.sync_common.shutil.which",
                           side_effect=lambda name: "/usr/bin/notify-send" if name == "notify-send" else None), \
                mock.patch("tools.sync_common.subprocess.run") as run:
            os.environ.pop("YDM_NOTIFY_DESKTOP", None)
            notify("ydm sync", "paused")
        run.assert_not_called()

    def test_service_turns_them_on(self):
        from tools.sync_common import notify
        with mock.patch.dict(os.environ, {"YDM_NOTIFY_DESKTOP": "1"}), \
                mock.patch("tools.sync_common.shutil.which",
                           side_effect=lambda name: "/usr/bin/notify-send" if name == "notify-send" else None), \
                mock.patch("tools.sync_common.subprocess.run") as run:
            notify("ydm sync", "paused")
        self.assertEqual(run.call_args[0][0], ["/usr/bin/notify-send", "--app-name=ydm", "ydm sync", "paused"])

    def test_termux_card_still_wins_on_the_device(self):
        from tools.sync_common import notify
        with mock.patch.dict(os.environ, {"YDM_NOTIFY_DESKTOP": "1"}), \
                mock.patch("tools.sync_common.shutil.which", return_value="/bin/termux-notification"), \
                mock.patch("tools.sync_common.subprocess.run") as run:
            notify("ydm sync", "paused")
        self.assertEqual(run.call_args[0][0][0], "/bin/termux-notification")


if __name__ == "__main__":
    unittest.main()
