#!/usr/bin/env bash
# Schedule ydm's bisync on a Linux desktop: a systemd *user* timer, the PC's
# counterpart of tools/termux/install_job.sh.
#
#   bash tools/linux/install_timer.sh install   # write the units, enable, start the timer
#   bash tools/linux/install_timer.sh status    # what systemd says, and the last runs
#   bash tools/linux/install_timer.sh remove    # stop and delete the units
#   bash tools/linux/install_timer.sh render    # print the units, change nothing
#
# The units are generated here rather than kept as templates in the repository:
# they carry this checkout's path and this machine's rclone, and a template that
# has to be edited by hand drifts from the copy that runs.
#
# Settings, read at install time and written into the service:
#   YDM_RCLONE       rclone binary (required unless `rclone` on PATH is >= 1.66 —
#                    older bisync aborts the whole run on one unreadable file)
#   YDM_LOCAL_ROOT   the mirror (default /data/ya_disk)
#   YDM_PERIOD       how often (default 30min; systemd time span)
#   YDM_UNIT         unit name (default ydm-bisync)
#
# The service only runs `sync_bisync.py run --apply`, which refuses to sync
# without a resync on record and with filters changed since it — the timer
# never establishes a baseline on its own.
set -euo pipefail

UNIT="${YDM_UNIT:-ydm-bisync}"
UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
YDM_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
LOCAL_ROOT="${YDM_LOCAL_ROOT:-/data/ya_disk}"
PERIOD="${YDM_PERIOD:-30min}"
RCLONE="${YDM_RCLONE:-$(command -v rclone || true)}"
PYTHON="$(command -v python3)"

rclone_ok() {
    local v
    v="$("$RCLONE" version 2>/dev/null | head -1 | sed -nE 's/^rclone v([0-9]+)\.([0-9]+).*/\1 \2/p')"
    [ -n "$v" ] || return 1
    set -- $v
    [ "$1" -gt 1 ] || { [ "$1" -eq 1 ] && [ "$2" -ge 66 ]; }
}

check_inputs() {
    if [ -z "$RCLONE" ] || ! rclone_ok; then
        echo "rclone '${RCLONE:-<none>}' is missing or older than 1.66; set YDM_RCLONE to a newer one." >&2
        exit 1
    fi
    [ -d "$LOCAL_ROOT" ] || { echo "Mirror $LOCAL_ROOT does not exist." >&2; exit 1; }
}

service_unit() {
    cat <<UNITEOF
# Generated by $YDM_DIR/tools/linux/install_timer.sh — re-run it instead of editing.
[Unit]
Description=ydm bisync of $LOCAL_ROOT
After=network-online.target

[Service]
Type=oneshot
WorkingDirectory=$YDM_DIR
Environment=YDM_RCLONE=$RCLONE
Environment=YDM_NOTIFY_DESKTOP=1
# Straight to Yandex, not through whatever proxy the login session exports:
# on 2026-10-29 a resync inherited https_proxy (a VPN exit abroad) and hung
# on its listings for half an hour without moving a byte.
UnsetEnvironment=http_proxy https_proxy all_proxy HTTP_PROXY HTTPS_PROXY ALL_PROXY
ExecStart=$PYTHON $YDM_DIR/tools/sync_bisync.py run --local-root $LOCAL_ROOT --apply --format text
Nice=10
IOSchedulingClass=idle
UNITEOF
}

timer_unit() {
    cat <<UNITEOF
# Generated by $YDM_DIR/tools/linux/install_timer.sh — re-run it instead of editing.
[Unit]
Description=ydm bisync every $PERIOD

[Timer]
OnBootSec=10min
OnUnitInactiveSec=$PERIOD

[Install]
WantedBy=timers.target
UNITEOF
}

install_units() {
    check_inputs
    mkdir -p "$UNIT_DIR"
    service_unit > "$UNIT_DIR/$UNIT.service"
    timer_unit > "$UNIT_DIR/$UNIT.timer"
    systemctl --user daemon-reload
    systemctl --user enable --now "$UNIT.timer"
    echo "Installed $UNIT.timer: every $PERIOD, rclone $("$RCLONE" version | head -1), mirror $LOCAL_ROOT"
    systemctl --user list-timers "$UNIT.timer" --no-pager
}

remove_units() {
    systemctl --user disable --now "$UNIT.timer" 2>/dev/null || true
    systemctl --user stop "$UNIT.service" 2>/dev/null || true
    rm -f "$UNIT_DIR/$UNIT.service" "$UNIT_DIR/$UNIT.timer"
    systemctl --user daemon-reload
    if systemctl --user list-unit-files "$UNIT.timer" --no-legend 2>/dev/null | grep -q .; then
        echo "$UNIT.timer is still known to systemd" >&2; exit 1
    fi
    echo "Removed $UNIT.timer and $UNIT.service"
}

case "${1:-}" in
    install) install_units ;;
    render) check_inputs; echo "# --- $UNIT.service"; service_unit; echo "# --- $UNIT.timer"; timer_unit ;;
    remove) remove_units ;;
    status)
        systemctl --user list-timers "$UNIT.timer" --no-pager || true
        systemctl --user status "$UNIT.service" --no-pager -n 15 || true ;;
    *) echo "usage: $0 install|render|status|remove" >&2; exit 2 ;;
esac
